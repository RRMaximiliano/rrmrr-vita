#!/bin/sh
# Writes the CV's version info from git:
#   vc.tex          read by the PDF footer (ignored by git)
#   rrmrr-vita.json read by rrmaximiliano.com/cv (published with the PDF)
# The commit and date are those of the last commit that changed the CV
# source, not HEAD, so committing the built PDF doesn't change them.
set -eu
cd "$(dirname "$0")"

repo="https://github.com/RRMaximiliano/rrmrr-vita"
set -- '*.tex' '*.sty' logo  # CV source

if ! git rev-parse --git-dir >/dev/null 2>&1; then
  : > vc.tex  # not a git checkout; the footer falls back to \today
  exit 0
fi

hash=$(git log -1 --format=%H -- "$@")
short=$(git log -1 --format=%h -- "$@")
date=$(git log -1 --format=%cs -- "$@")
# Built with uncommitted edits: use today's date, as \today did before.
if [ -n "$(git status --porcelain -- "$@")" ]; then
  date=$(date +%F)
fi

cat > vc.tex <<TEX
% Generated by vc.sh; do not edit.
\\def\\cvcommit{$short}
\\def\\cvcommitfull{$hash}
\\def\\cvdate{\\DTMdate{$date}}
TEX

cat > rrmrr-vita.json <<JSON
{
  "updated": "$date",
  "commit": "$short",
  "commit_url": "$repo/tree/$hash"
}
JSON
